#!/usr/bin/env python3
"""Generate and validate the 3b audit-answer table in MILESTONE2.md.

Findings live in docs/audit-answers.json. A "fixed" finding names the commit by its
subject; this script resolves it to a SHA and refuses to emit a table unless:

  * the subject matches exactly one commit,
  * that commit is an ancestor of HEAD,
  * its diff touches frontend/tests/acceptance/,
  * every rejected finding carries a one-line reason,
  * every finding id appears once.

Usage:
  python3 scripts/gen_audit_answers.py            # write the table into MILESTONE2.md
  python3 scripts/gen_audit_answers.py --check    # validate what is already in the file
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "docs" / "audit-answers.json"
REPORT = ROOT / "MILESTONE2.md"
LOCKED_DIR = "frontend/tests/acceptance/"
BEGIN = "<!-- BEGIN AUDIT ANSWERS (generated by scripts/gen_audit_answers.py) -->"
END = "<!-- END AUDIT ANSWERS -->"


def git(*args: str) -> str:
    return subprocess.run(("git",) + args, cwd=ROOT, check=True,
                          capture_output=True, text=True).stdout.strip()


def resolve(subject: str) -> str:
    out = git("log", "--all", "--format=%H%x09%s", "--fixed-strings", f"--grep={subject}")
    rows = [line.split("\t", 1) for line in out.splitlines() if line]
    exact = [sha for sha, subj in rows if subj == subject]
    if len(exact) != 1:
        sys.exit(f"error: subject {subject!r} matches {len(exact)} exact commits, expected 1")
    sha = exact[0]
    try:
        git("merge-base", "--is-ancestor", sha, "HEAD")
    except subprocess.CalledProcessError:
        sys.exit(f"error: {sha[:7]} ({subject!r}) is not an ancestor of HEAD")
    changed = git("diff", "--name-only", f"{sha}^..{sha}").splitlines()
    if not any(path.startswith(LOCKED_DIR) for path in changed):
        sys.exit(f"error: {sha[:7]} does not touch {LOCKED_DIR}")
    return sha


def build_rows() -> list[str]:
    data = json.loads(MANIFEST.read_text())
    rows, seen = [], set()
    for finding in data["findings"]:
        fid = finding["id"]
        if fid in seen:
            sys.exit(f"error: finding {fid} listed twice")
        seen.add(fid)
        verdict = finding["verdict"]
        reason = finding["reason"].strip()
        if not reason:
            sys.exit(f"error: finding {fid} has no reason")
        if verdict == "fixed":
            sha = resolve(finding["commit_subject"])
            rows.append(f"| {fid} | Fixed in `{sha[:7]}` — {reason} |")
        elif verdict == "rejected":
            rows.append(f"| {fid} | Rejected — {reason} |")
        else:
            sys.exit(f"error: finding {fid} has unknown verdict {verdict!r}")
    return rows


def check_file(rows: list[str]) -> None:
    text = REPORT.read_text()
    existing = [line for line in text.splitlines() if line.startswith("| ") and "—" in line]
    for row in rows:
        sha = re.search(r"`([0-9a-f]{7})`", row)
        if sha and row not in text:
            sys.exit(f"error: MILESTONE2.md is missing row: {row}")
        if sha:
            full = git("rev-parse", "--verify", sha.group(1)).strip()
            git("merge-base", "--is-ancestor", full, "HEAD")
    print(f"ok: {len(rows)} rows present; every cited SHA resolves and is an ancestor of HEAD")


def main() -> None:
    rows = build_rows()
    table = "\n".join([BEGIN, "", "| Finding | Resolution |", "|---|---|"] + rows + ["", END])

    if "--check" in sys.argv:
        check_file(rows)
        return

    if not REPORT.exists():
        sys.exit("error: MILESTONE2.md does not exist yet; create it with the markers first")
    text = REPORT.read_text()
    if BEGIN in text and END in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), table, text, flags=re.S)
    else:
        text = text.rstrip() + "\n\n" + table + "\n"
    REPORT.write_text(text)
    print(f"wrote {len(rows)} rows into {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
